#!/usr/bin/env bash
set -euo pipefail

# Usage:
#   install-agent-credentials.sh --install
#   install-agent-credentials.sh --check
#   ... [--hook <path>] [--keychain <path>] [--account <name>]
#
# The generated hook contains Keychain lookup commands, never credential
# values. It reads GH_TOKEN for every project and GITHUB_PACKAGES_TOKEN only
# when the loader marks a Maven/package-registry project.

mode=""
hook="${FORGELET_AGENT_CREDENTIAL_HOOK:-${HOME:-}/.config/forgelet/agent-credentials.sh}"
keychain="${FORGELET_AGENT_KEYCHAIN:-${HOME:-}/Library/Keychains/forgelet-devbox.keychain-db}"
account="${FORGELET_AGENT_KEYCHAIN_ACCOUNT:-$(id -un)}"
security_command="${SWARMFORGE_SECURITY_COMMAND:-security}"
gh_command="${SWARMFORGE_GH_COMMAND:-gh}"

fail() {
  echo "install-agent-credentials: $1" >&2
  exit 1
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --install|--check)
      [[ -z "$mode" ]] || fail "choose exactly one of --install or --check"
      mode="${1#--}"
      shift
      ;;
    --hook|--keychain|--account)
      [[ $# -ge 2 && -n "$2" ]] || fail "$1 needs a value"
      case "$1" in
        --hook) hook="$2" ;;
        --keychain) keychain="$2" ;;
        --account) account="$2" ;;
      esac
      shift 2
      ;;
    *)
      fail "unknown argument: $1"
      ;;
  esac
done

[[ -n "$mode" ]] || fail "choose --install or --check"
[[ -n "$hook" ]] || fail "credential hook path is empty"
[[ -n "$keychain" ]] || fail "Keychain path is empty"
[[ -n "$account" ]] || fail "Keychain account is empty"
command -v "$security_command" >/dev/null 2>&1 ||
  fail "security command is unavailable"
command -v "$gh_command" >/dev/null 2>&1 ||
  fail "gh command is unavailable"

shell_quote() {
  local value="$1"
  printf "'%s'" "${value//\'/\'\\\'\'}"
}

keychain_item_available() {
  local service="$1"
  "$security_command" find-generic-password \
    -a "$account" -s "$service" -w "$keychain" >/dev/null 2>&1
}

require_keychain_items() {
  keychain_item_available GH_TOKEN ||
    fail "Keychain item GH_TOKEN is missing or unavailable"
  keychain_item_available GITHUB_PACKAGES_TOKEN ||
    fail "Keychain item GITHUB_PACKAGES_TOKEN is missing or unavailable"
}

hook_text() {
  cat <<EOF
#!/usr/bin/env bash
# Generated by install-agent-credentials.sh. Contains lookup commands, not tokens.
set -euo pipefail
hook_keychain=$(shell_quote "$keychain")
hook_account=$(shell_quote "$account")
hook_security=$(shell_quote "$security_command")
read_agent_credential() {
  "\$hook_security" find-generic-password \\
    -a "\$hook_account" -s "\$1" -w "\$hook_keychain"
}
GH_TOKEN="\$(read_agent_credential GH_TOKEN)"
export GH_TOKEN
if [[ "\${SWARMFORGE_PROJECT_NEEDS_PACKAGES_TOKEN:-}" == "1" ]]; then
  GITHUB_PACKAGES_TOKEN="\$(read_agent_credential GITHUB_PACKAGES_TOKEN)"
  export GITHUB_PACKAGES_TOKEN
fi
EOF
}

validate_hook() {
  [[ -L "$hook" ]] && fail "credential hook must not be a symbolic link"
  [[ -f "$hook" && -r "$hook" ]] || fail "cannot read credential hook"
  local owner mode_bits
  owner="$(stat -f '%u' "$hook" 2>/dev/null || stat -c '%u' "$hook" 2>/dev/null)" ||
    fail "cannot inspect credential hook ownership"
  mode_bits="$(stat -f '%Lp' "$hook" 2>/dev/null || stat -c '%a' "$hook" 2>/dev/null)" ||
    fail "cannot inspect credential hook permissions"
  [[ "$owner" == "$(id -u)" ]] ||
    fail "credential hook must be owned by the current user"
  (( (8#$mode_bits & 077) == 0 )) ||
    fail "credential hook must be owner-only"
  bash -n "$hook" || fail "malformed shell syntax in credential hook"
}

install_hook() {
  fs_parent="$(dirname "$hook")"
  mkdir -p "$fs_parent"
  chmod 700 "$fs_parent"
  local tmp
  tmp="$(mktemp "$fs_parent/.agent-credentials.XXXXXX")"
  trap 'rm -f "$tmp"' EXIT
  umask 077
  hook_text >"$tmp"
  chmod 600 "$tmp"
  mv "$tmp" "$hook"
  trap - EXIT
}

require_keychain_items

if [[ "$mode" == "install" ]]; then
  if [[ -e "$hook" || -L "$hook" ]]; then
    validate_hook
  else
    install_hook
  fi
fi

validate_hook

if ! gh_token="$(
  SWARMFORGE_PROJECT_NEEDS_PACKAGES_TOKEN=0 bash -c '
    source "$1" >/dev/null 2>&1
    [[ -n "${GH_TOKEN:-}" ]] || exit 1
    printf "%s" "$GH_TOKEN"
  ' _ "$hook"
)"; then
  fail "credential hook did not load GH_TOKEN"
fi

if ! GH_TOKEN="$gh_token" "$gh_command" auth setup-git --hostname github.com >/dev/null 2>&1; then
  fail "gh could not configure Git authentication for GH_TOKEN"
fi
if ! GH_TOKEN="$gh_token" "$gh_command" auth status --hostname github.com >/dev/null 2>&1; then
  fail "gh could not verify GitHub access for GH_TOKEN"
fi
if ! SWARMFORGE_PROJECT_NEEDS_PACKAGES_TOKEN=1 bash -c '
  source "$1" >/dev/null 2>&1
  [[ -n "${GITHUB_PACKAGES_TOKEN:-}" ]]
' _ "$hook"; then
  fail "credential hook did not load GITHUB_PACKAGES_TOKEN for a package-registry project"
fi

echo "install-agent-credentials: $mode ok"
echo "install-agent-credentials: GH_TOKEN present"
echo "install-agent-credentials: GITHUB_PACKAGES_TOKEN present"
